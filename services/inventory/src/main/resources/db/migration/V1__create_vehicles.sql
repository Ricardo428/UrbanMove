-- Catálogo de recursos. Inventory es su único dueño (docs/data-ownership.md).
-- La zona de puesta en servicio no se guarda: viaja solo en VehiclePurchased y la ubicación es de Availability.
CREATE TABLE vehicles (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
    vehicle_type          VARCHAR(16)              NOT NULL CHECK (vehicle_type IN ('BIKE', 'SCOOTER')),
    serial_number         VARCHAR(64)              NOT NULL UNIQUE,
    model                 VARCHAR(128)             NOT NULL,
    purchase_date         DATE                     NOT NULL,
    administrative_status VARCHAR(16)              NOT NULL DEFAULT 'ACTIVE'
                              CHECK (administrative_status IN ('ACTIVE', 'RETIRED')),
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
