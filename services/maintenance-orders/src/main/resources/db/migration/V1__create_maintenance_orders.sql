-- Órdenes de mantenimiento. Maintenance Orders es su única dueña (docs/data-ownership.md).
-- El identificador público es "mo-" + id. El estado del recurso no está aquí: es de availability.
-- operator_id es el usuario del token que hizo withdraw: vacío solo mientras la orden está OPEN.
-- task es la tarea que registra el operario en start: vacía hasta IN_PROGRESS.
-- zone_id es la zona en la que queda el recurso al completar la orden.
CREATE TABLE maintenance_orders (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 310) PRIMARY KEY,
    vehicle_id            VARCHAR(64)              NOT NULL,
    reason                VARCHAR(16)              NOT NULL CHECK (reason IN ('BATTERY_LOW', 'FAULT', 'USAGE')),
    battery_level_percent INT CHECK (battery_level_percent BETWEEN 0 AND 100),
    status                VARCHAR(16)              NOT NULL CHECK (status IN (
                              'OPEN', 'WITHDRAWN', 'IN_PROGRESS', 'COMPLETED')),
    task                  VARCHAR(16) CHECK (task IN ('RECHARGE', 'REPAIR', 'REVIEW')),
    operator_id           VARCHAR(64),
    zone_id               VARCHAR(64),
    detected_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    withdrawn_at          TIMESTAMP WITH TIME ZONE,
    started_at            TIMESTAMP WITH TIME ZONE,
    completed_at          TIMESTAMP WITH TIME ZONE,
    CHECK ((status = 'OPEN') = (operator_id IS NULL)),
    CHECK ((status IN ('OPEN', 'WITHDRAWN')) = (task IS NULL)),
    CHECK ((status = 'COMPLETED') = (zone_id IS NOT NULL))
);

-- Como mucho una orden activa por recurso. Un segundo VehicleBatteryLow del mismo recurso inserta 0 filas con
-- ON CONFLICT DO NOTHING, aunque dos réplicas lo procesen a la vez. Al pasar a COMPLETED la orden sale del índice.
CREATE UNIQUE INDEX maintenance_orders_one_active_per_vehicle
    ON maintenance_orders (vehicle_id) WHERE status <> 'COMPLETED';

-- GET /maintenance-orders?status=..., las más antiguas primero.
CREATE INDEX maintenance_orders_by_status ON maintenance_orders (status, created_at);

-- GET /maintenance-orders?vehicleId=... y la comprobación de detecciones atrasadas (¿hay una orden completada
-- del recurso posterior a detectedAt?).
CREATE INDEX maintenance_orders_by_vehicle ON maintenance_orders (vehicle_id, completed_at);
