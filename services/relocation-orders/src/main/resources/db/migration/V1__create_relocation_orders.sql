-- Órdenes de recolocación. Relocation Orders es su única dueña (docs/data-ownership.md).
-- El identificador público es "ro-" + id. El estado de los recursos no está aquí: es de availability.
-- operator_id es el usuario del token que hizo pickup: vacío mientras la orden está OPEN, y también si se
-- cancela, porque solo se cancela desde OPEN.
CREATE TABLE relocation_orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 210) PRIMARY KEY,
    from_zone_id VARCHAR(64)              NOT NULL,
    to_zone_id   VARCHAR(64)              NOT NULL,
    vehicle_type VARCHAR(16)              NOT NULL CHECK (vehicle_type IN ('BIKE', 'SCOOTER')),
    quantity     INT                      NOT NULL CHECK (quantity > 0),
    status       VARCHAR(16)              NOT NULL CHECK (status IN (
                     'OPEN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    operator_id  VARCHAR(64),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    picked_up_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    CHECK (from_zone_id <> to_zone_id),
    CHECK ((status IN ('OPEN', 'CANCELLED')) = (operator_id IS NULL))
);

-- Como mucho una orden activa por zona destino y tipo (decisión 4 del contrato). Un segundo
-- DemandHotspotDetected de la misma zona inserta 0 filas con ON CONFLICT DO NOTHING, aunque dos réplicas
-- lo procesen a la vez. Al pasar a COMPLETED o CANCELLED la orden sale del índice.
CREATE UNIQUE INDEX relocation_orders_one_active_per_zone
    ON relocation_orders (to_zone_id, vehicle_type) WHERE status IN ('OPEN', 'IN_PROGRESS');

-- GET /relocation-orders?status=..., las más antiguas primero.
CREATE INDEX relocation_orders_by_status ON relocation_orders (status, created_at);

-- Recursos de cada orden. Se inserta la fila ANTES de pedir a availability el WITHDRAWN: el PUT /state es
-- idempotente y no distingue "lo retiré yo" de "lo retiró otra orden", así que quien reclama el recurso es
-- esta tabla. Si availability lo rechaza, se borra la fila. Al completar la orden, active pasa a false.
CREATE TABLE relocation_order_vehicles (
    order_id   BIGINT                   NOT NULL REFERENCES relocation_orders (id),
    vehicle_id VARCHAR(64)              NOT NULL,
    active     BOOLEAN                  NOT NULL DEFAULT true,
    claimed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    PRIMARY KEY (order_id, vehicle_id)
);

-- Un recurso no puede estar en dos órdenes activas a la vez, aunque tengan destinos distintos.
CREATE UNIQUE INDEX relocation_order_vehicles_one_active_order
    ON relocation_order_vehicles (vehicle_id) WHERE active;
