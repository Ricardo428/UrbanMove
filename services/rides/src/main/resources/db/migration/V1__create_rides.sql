-- Viajes. Rides es su única dueña (docs/data-ownership.md).
-- origin_zone_id se rellena con la respuesta de availability cuando el viaje se acepta.
-- Los campos de fin (end_time ... battery_level_percent) se rellenan al finalizar.
CREATE TABLE rides (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 5501) PRIMARY KEY,
    vehicle_id            VARCHAR(64)              NOT NULL,
    user_id               VARCHAR(64)              NOT NULL,
    reservation_id        VARCHAR(64),
    status                VARCHAR(16)              NOT NULL CHECK (status IN (
                              'STARTING', 'IN_PROGRESS', 'COMPLETED', 'REJECTED')),
    origin_zone_id        VARCHAR(64),
    start_time            TIMESTAMP WITH TIME ZONE NOT NULL,
    destination_zone_id   VARCHAR(64),
    end_time              TIMESTAMP WITH TIME ZONE,
    duration_minutes      INT,
    zone_validated        BOOLEAN,
    preliminary_cost      NUMERIC(8, 2),
    battery_level_percent INT
);
