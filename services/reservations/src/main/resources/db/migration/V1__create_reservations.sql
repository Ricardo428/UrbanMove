-- Reservas de vehículos. Reservations es su única dueña (docs/data-ownership.md).
-- zone_id se rellena con la respuesta de availability cuando la reserva se acepta.
CREATE TABLE reservations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 7001) PRIMARY KEY,
    vehicle_id VARCHAR(64)              NOT NULL,
    user_id    VARCHAR(64)              NOT NULL,
    zone_id    VARCHAR(64),
    status     VARCHAR(16)              NOT NULL CHECK (status IN (
                   'PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'REJECTED', 'USED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- La Lambda de expiración buscará las reservas activas ya vencidas.
CREATE INDEX reservations_active_expiry ON reservations (expires_at) WHERE status IN ('PENDING', 'CONFIRMED');
